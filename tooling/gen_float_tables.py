#!/usr/bin/env python3
"""Generate lib/1-primitives/floats/impl/power5_tables.hpp: Ryu's 128-bit powers of 5.

Usage: gen_float_tables.py [lib] [--clean | --fclean]   (default: <repo>/src/lib)

The shortest float-to-text conversion (Ryu, Ulf Adams 2018) multiplies the mantissa by 5^q or by
2^k / 5^q kept to 125 bits, here computed exactly with Python integers:
  POWER5_INVERSE[q] = floor(2^(bits(5^q) - 1 + 125) / 5^q) + 1    q in [0, 342)
  POWER5[i]         = 5^i shifted to exactly 125 bits              i in [0, 326)
each as {low 64 bits, high 64 bits}. pow5bits(e) = ((e * 1217359) >> 19) + 1, the bit length of
5^e that the C++ side computes, is checked against the exact value. Never edit the header.
"""

import argparse
import os
import sys

sys.dont_write_bytecode = True
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import cleanup  # noqa: E402

AP = argparse.ArgumentParser(description=__doc__.split('\n')[0])
AP.add_argument('lib', nargs='?', default=os.path.join(cleanup.REPO, 'src', 'lib'))
cleanup.add_arguments(AP)
OPTS = AP.parse_args()
OUT = os.path.join(OPTS.lib, '1-primitives', 'floats', 'impl', 'power5_tables.hpp')

if OPTS.clean or OPTS.fclean:
	sys.exit(cleanup.run(OPTS, 'gen_float_tables', cleanup.bytecode(), [OUT]))

BITS = 125
INVERSE_COUNT = 342
POWER_COUNT = 326
MASK = (1 << 64) - 1


def pow5bits(e):
	return ((e * 1217359) >> 19) + 1


for e in range(1, 3529):
	assert pow5bits(e) == (5 ** e).bit_length(), e

inverse = []
for q in range(INVERSE_COUNT):
	p = 5 ** q
	v = (1 << (p.bit_length() - 1 + BITS)) // p + 1
	assert v.bit_length() <= BITS + 1
	inverse.append(v)

power = []
for i in range(POWER_COUNT):
	p = 5 ** i
	s = p.bit_length() - BITS
	v = p >> s if s > 0 else p << -s
	assert v.bit_length() == BITS
	power.append(v)


def rows(values):
	return '\n'.join(f'\t\t\t{{{v & MASK}U, {v >> 64}U}},' for v in values)


TEXT = f"""#ifndef ca_primitives_floats_impl_power5_tables_hpp
#define ca_primitives_floats_impl_power5_tables_hpp

#include "1-primitives/integers/u64.hpp"
#include "1-primitives/integers/usz.hpp"

// Generated by tooling/gen_float_tables.py. Do not edit.


// -- CA NAMESPACE -----------------------------------------------------------

namespace ca {{


	// -- POWER5 TABLES ------------------------------------------------------

	namespace impl {{

		/* @DOC Bits kept of each power of 5 and of each inverse. */
		inline constexpr ca::usz POWER5_BITS = {BITS}U;

		/* @DOC floor(2^(bits(5^q) - 1 + {BITS}) / 5^q) + 1, q in [0, {INVERSE_COUNT}): {{low, high}}. */
		inline constexpr ca::u64 POWER5_INVERSE[{INVERSE_COUNT}][2] = {{
{rows(inverse)}
		}};

		/* @DOC 5^i shifted to exactly {BITS} bits, i in [0, {POWER_COUNT}): {{low, high}}. */
		inline constexpr ca::u64 POWER5[{POWER_COUNT}][2] = {{
{rows(power)}
		}};

	}} // namespace impl

}} // namespace ca

#endif // ca_primitives_floats_impl_power5_tables_hpp
"""

os.makedirs(os.path.dirname(OUT), exist_ok=True)
old = open(OUT).read() if os.path.exists(OUT) else None
if old != TEXT:
	with open(OUT, 'w') as f:
		f.write(TEXT)
	print(f'gen_float_tables: wrote {os.path.relpath(OUT, cleanup.REPO)}')
else:
	print('gen_float_tables: up to date')
