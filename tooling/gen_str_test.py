#!/usr/bin/env python3
"""Writes tests/str_python.cpp: ca::str and ca::sv against CPython. Every expectation is
what the running Python returns for the same call, so the test pins Python semantics.

    tooling/gen_str_test.py [--clean | --fclean]

--clean leaves nothing to remove but bytecode; --fclean also removes tests/str_python.cpp
(see cleanup.py).
"""

import argparse
import os
import sys

sys.dont_write_bytecode = True
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import cleanup  # noqa: E402

OUT = os.path.join(cleanup.REPO, "tests", "str_python.cpp")
ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
cleanup.add_arguments(ap)
opts = ap.parse_args()
if opts.clean or opts.fclean:
    sys.exit(cleanup.run(opts, "gen_str_test", cleanup.bytecode(), [OUT]))

# Generates tests/str_python.cpp: each case's expectation is computed by CPython.
def lit(s):
    out = '"'
    for ch in s:
        o = ord(ch)
        if ch in '"\\': out += '\\' + ch
        elif 32 <= o < 127: out += ch
        else: out += '\\x%02x""' % o
    return out + '"'
inputs = ["", " ", "Hello, World", "  padded\t\n", "a,b,,c,", "one two  three ", "line1\nline2\r\nline3\rend\n", "\x0bv\x0cf\x1cfs", "ABC", "abc", "Abc Def", "aBc DeF", "ABC def", "123", "12a", "_ident9", "9ident", "it's a dog's life", "x\ty\tzz\tw", "-42", "+7", "tab\there\nnext\tt", "   ", "a  b", "Title Case Words", "hello\x00world", "\x7f"]
cases = []
def exp(s):
    return f"ca::sv::str{{{lit(s)}, {len(s.encode())}U}}"
def add(expr, expected):
    cases.append((expr, expected))
for s in inputs:
    L = lit(s)
    v = f"ca::sv::str{{{L}, {len(s)}U}}"
    for pred in ["isalpha", "isalnum", "isdecimal", "isdigit", "isnumeric", "isspace", "isupper", "islower", "istitle", "isprintable", "isascii", "isidentifier"]:
        name = "is_" + pred[2:]
        add(f"{v}.{name}()", "true" if getattr(s, pred)() else "false")
    add(f"{v}.strip()", exp(s.strip()))
    add(f"{v}.strip_start()", exp(s.lstrip()))
    add(f"{v}.strip_end()", exp(s.rstrip()))
    add(f"{v}.strip(\"ad,\")", exp(s.strip("ad,")))
    add(f"pieces({v}.split())", exp("|".join(s.split())))
    add(f"pieces({v}.split(\",\"))", exp("|".join(s.split(","))))
    add(f"pieces({v}.split(\" \", 1U))", exp("|".join(s.split(" ", 1))))
    add(f"pieces({v}.split_lines())", exp("|".join(s.splitlines())))
    add(f"pieces({v}.split_lines(true))", exp("|".join(s.splitlines(True))))
    add(f"{v}.count(\"a\")", f"{s.count('a')}U")
    add(f"{v}.count(\"\")", f"{s.count('')}U")
    p = s.partition(",")
    add(f"parts({v}.partition(\",\"))", exp("|".join(p)))
    p = s.rpartition(",")
    add(f"parts({v}.partition_last(\",\"))", exp("|".join(p)))
    add(f"{v}.strip_prefix(\"He\")", exp(s.removeprefix("He")))
    for meth, py in [("upper", "upper"), ("lower", "lower"), ("title", "title"), ("capitalize", "capitalize"), ("swap_case", "swapcase"), ("case_fold", "casefold")]:
        add(f"owned({v}).{meth}()", exp(getattr(s, py)()))
    add(f"owned({v}).replace(\"a\", \"XY\")", exp(s.replace("a", "XY")))
    add(f"owned({v}).replace(\"\", \"-\", 3U)", exp(s.replace("", "-", 3)))
    add(f"owned({v}).replace(\" \", \"\")", exp(s.replace(" ", "")))
    add(f"owned({v}).center(15U, U'*')", exp(s.center(15, "*")))
    add(f"owned({v}).center(4U)", exp(s.center(4)))
    add(f"owned({v}).justify_left(14U, U'.')", exp(s.ljust(14, ".")))
    add(f"owned({v}).justify_right(14U)", exp(s.rjust(14)))
    add(f"owned({v}).zero_fill(6U)", exp(s.zfill(6)))
    add(f"owned({v}).expand_tabs()", exp(s.expandtabs()))
    add(f"owned({v}).expand_tabs(3U)", exp(s.expandtabs(3)))
    add(f"owned({v}).repeat(2U)", exp(s * 2))
lines = []
for i, (expr, expected) in enumerate(cases):
    lines.append(f"\tfailed |= !same({expr}, {expected}) ? report({i}) : 0; // {expr} == {expected}")
out = """// expect: exit 0
// Generated by tooling/gen_str_test.py: every expectation is what CPython's str returns.
#include "5-collections/string/str.hpp"
#include "6-resources/print/print.hpp"

static auto report(const int index) noexcept -> int {

	static_cast<void>(ca::print("case {} failed; ", index));
	return 1;
}

static auto same(const ca::sv::str got, const ca::sv::str expected) noexcept -> bool {
	return got == expected;
}

static auto same(const ca::result<ca::str>& got, const ca::sv::str expected) noexcept -> bool {
	return got && got->view() == expected;
}

static auto same(const bool got, const bool expected) noexcept -> bool {
	return got == expected;
}

static auto same(const ca::usz got, const ca::usz expected) noexcept -> bool {
	return got == expected;
}

static char joined[4096];

static auto pieces(const ca::sv::splits<char> split) noexcept -> ca::sv::str {

	ca::usz size = 0U;
	bool first = true;
	for (const ca::sv::str piece : split) {
		if (!first)
			joined[size++] = '|';
		first = false;
		for (const char c : piece)
			joined[size++] = c;
	}
	return ca::sv::str{joined, size};
}

static auto parts(const ca::sv::partitioned<char> parted) noexcept -> ca::sv::str {

	ca::usz size = 0U;
	const ca::sv::str three[3] = {parted.before(), parted.separator(), parted.after()};
	for (const ca::sv::str piece : three) {
		for (const char c : piece)
			joined[size++] = c;
		joined[size++] = '|';
	}
	return ca::sv::str{joined, size - 1U};
}

static auto owned(const ca::sv::str text) noexcept -> ca::str {

	auto made = ca::str::make(text);
	return made ? static_cast<ca::str&&>(*made) : ca::str{};
}

auto main(void) -> int {
	int failed = 0;
""" + "\n".join(lines) + """
	return failed;
}
"""
open(OUT, "w").write(out)
print(len(cases), "cases")
