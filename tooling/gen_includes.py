#!/usr/bin/env python3
"""Generate the include facade src/lib/ca/<name>.hpp from the layout of src/lib.

Usage: gen_includes.py [--check | --clean | --fclean]

Users write `#include "ca/print.hpp"` instead of "6-resources/print/print.hpp". One
umbrella per name, every name derived from the tree, nothing configured by hand:

	category   each directory directly under a layer (memory, io, fs, format, print,
	           traits, ...), merged across layers: ca/memory.hpp is 1-primitives/memory,
	           3-system/memory and 4-lifecycle/memory together
	entity     each header at a layer's root (dynamic_array, optional, result, make, ...),
	           and each header of the upper layers (>= 5: path, stream, descriptor, ...);
	           tag types (*_t.hpp) come with their constant (nullopt, in_place)
	           a name that is also a category joins it (ca/error.hpp: ca::error, errc, ...)
	all        ca/all.hpp, the whole library

impl/ directories and headers are internal and never listed. An umbrella names only
the headers no other member already includes, so it stays short and never pulls a
platform-specific header its owner selects. Files are rewritten only when they change;
stale ones are removed. --check writes nothing and exits 1 when the facade is out of date.
--clean leaves nothing to remove but bytecode; --fclean also removes every umbrella (files
carrying the generated mark) and src/lib/ca/ once empty (see cleanup.py).
"""

import argparse
import os
import re
import sys
from collections import defaultdict

sys.dont_write_bytecode = True
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import cleanup  # noqa: E402

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LIB = os.path.join(REPO, 'src', 'lib')
FACADE = 'ca'
OUT = os.path.join(LIB, FACADE)
LAYER = re.compile(r'(\d+)-[a-z]+$')
INCLUDE = re.compile(r'^\s*#\s*include\s*"([^"]+)"', re.M)
ENTITY_LAYER = 5
MARK = 'Generated by tooling/gen_includes.py'
WIDTH = 95


def scan():
	headers = {}
	for layer in sorted(d for d in os.listdir(LIB) if LAYER.match(d)):
		for d, dirs, names in os.walk(os.path.join(LIB, layer)):
			dirs[:] = sorted(x for x in dirs if x != 'impl')
			for n in sorted(names):
				if n.endswith('.hpp'):
					path = os.path.join(d, n)
					rel = os.path.relpath(path, LIB).replace(os.sep, '/')
					with open(path) as f:
						headers[rel] = set(INCLUDE.findall(f.read()))
	return headers


def groups_of(headers):
	groups = defaultdict(set)
	sources = defaultdict(set)
	for rel in headers:
		parts = rel.split('/')
		layer = int(parts[0].split('-')[0])
		stem = parts[-1][:-4]
		if len(parts) == 2:
			if stem.endswith('_t'):
				continue
			groups[stem].add(rel)
			sources[stem].add(rel)
			continue
		groups[parts[1]].add(rel)
		sources[parts[1]].add(parts[0] + '/' + parts[1] + '/')
		if layer >= ENTITY_LAYER:
			groups[stem].add(rel)
			sources[stem].add(rel)
	for name, origin in sources.items():
		dirs = [o for o in origin if o.endswith('/')]
		sources[name] = {o for o in origin if not any(o.startswith(d) for d in dirs) or o in dirs}
	groups['all'] = set(headers)
	sources['all'] = {'the whole library'}
	return groups, sources


def roots(members, headers):
	included = set()
	for m in members:
		included |= headers[m] & members
	return sorted(members - included, key=lambda r: (int(r.split('-')[0]), r))


def wrap(text, first, rest):
	lines, line = [], first
	for word in text.split(' '):
		if len(line) + 1 + len(word) > WIDTH:
			lines.append(line)
			line = rest + word
		else:
			line = f'{line} {word}' if line.strip() else line + word
	lines.append(line)
	return '\n'.join(lines)


def render(name, members, origin):
	guard = f'ca_include_{re.sub(r"[^a-z0-9]+", "_", name)}_hpp'
	what = ', '.join(sorted(origin, key=lambda r: (int(r.split('-')[0]) if r[0].isdigit() else 0, r)))
	doc = wrap(f'@DOC `#include "{FACADE}/{name}.hpp"`: {what}. {MARK}; do not edit. */', '/*', '   ')
	body = '\n'.join(f'#include "{m}"' for m in members)
	return f'{doc}\n#ifndef {guard}\n#define {guard}\n\n{body}\n\n#endif // {guard}\n'


def umbrellas():
	if not os.path.isdir(OUT):
		return []
	found = []
	for n in sorted(os.listdir(OUT)):
		with open(os.path.join(OUT, n)) as f:
			if MARK in ' '.join(f.read().split()):
				found.append(os.path.join(OUT, n))
	return found


def main(argv):
	ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
	ap.add_argument('--check', action='store_true', help='exit 1 if the facade is out of date')
	cleanup.add_arguments(ap)
	opts = ap.parse_args(argv)
	if opts.clean or opts.fclean:
		return cleanup.run(opts, 'includes', cleanup.bytecode(), umbrellas, [OUT])

	headers = scan()
	groups, sources = groups_of(headers)
	wanted = {f'{name}.hpp': render(name, roots(members, headers), sources[name]) for name, members in groups.items()}

	stale = [n for n in map(os.path.basename, umbrellas()) if n not in wanted]
	changed = []
	for n, content in sorted(wanted.items()):
		path = os.path.join(OUT, n)
		old = open(path).read() if os.path.exists(path) else None
		if old != content:
			changed.append(n)

	if opts.check:
		for n in changed:
			print(f'  STALE  {FACADE}/{n}')
		for n in stale:
			print(f'  EXTRA  {FACADE}/{n}')
		if changed or stale:
			print('includes: out of date, run `make includes`')
			return 1
		print(f'includes: {len(wanted)} umbrellas up to date')
		return 0

	os.makedirs(OUT, exist_ok=True)
	for n in changed:
		with open(os.path.join(OUT, n), 'w') as f:
			f.write(wanted[n])
	for n in stale:
		os.remove(os.path.join(OUT, n))
	if changed or stale:
		print(f'includes: {len(changed)} written, {len(stale)} removed, {len(wanted)} umbrellas')
	return 0


if __name__ == '__main__':
	sys.exit(main(sys.argv[1:]))
